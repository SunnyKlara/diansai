/*
 * gc9a01.c - GC9A01 240x240 round color TFT for MSPM0G3507 (driverlib, no framebuffer).
 * Init sequence ported from the 校赛B STM32 project; SPI/GPIO/delay use MSPM0 driverlib.
 * Pins come from SysConfig (ti_msp_dl_config.h): LCD_SPI_INST(SPI1) + GPIO_LCD_* .
 */
#include "ti_msp_dl_config.h"
#include "gc9a01.h"

#define CPUCLK_HZ   32000000UL      /* default MCLK (SYSCTL forceDefaultClkConfig) */
#define LCD_MADCTL  0xC8            /* MY+MX+BGR, matches 校赛B (panel orient) */

static void delay_ms(uint32_t ms) { while (ms--) delay_cycles(CPUCLK_HZ / 1000UL); }

/* ---- control pins ---- */
#define CS_L()   DL_GPIO_clearPins(GPIO_LCD_PORT, GPIO_LCD_LCD_CS_PIN)
#define CS_H()   DL_GPIO_setPins  (GPIO_LCD_PORT, GPIO_LCD_LCD_CS_PIN)
#define DC_CMD() DL_GPIO_clearPins(GPIO_LCD_PORT, GPIO_LCD_LCD_DC_PIN)
#define DC_DAT() DL_GPIO_setPins  (GPIO_LCD_PORT, GPIO_LCD_LCD_DC_PIN)
#define RES_L()  DL_GPIO_clearPins(GPIO_LCD_PORT, GPIO_LCD_LCD_RES_PIN)
#define RES_H()  DL_GPIO_setPins  (GPIO_LCD_PORT, GPIO_LCD_LCD_RES_PIN)

static inline void spi_wr(uint8_t b) { DL_SPI_transmitDataBlocking8(LCD_SPI_INST, b); }
static inline void spi_done(void)    { while (DL_SPI_isBusy(LCD_SPI_INST)) {} }

static void wr_cmd(uint8_t c) { DC_CMD(); CS_L(); spi_wr(c); spi_done(); CS_H(); }
static void wr_dat(uint8_t v) { DC_DAT(); CS_L(); spi_wr(v); spi_done(); CS_H(); }

