static void gc9a01_set_window(uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1)
{
    wr_cmd(0x2A);
    DC_DAT(); CS_L();
    spi_wr(x0 >> 8); spi_wr(x0 & 0xFF); spi_wr(x1 >> 8); spi_wr(x1 & 0xFF);
    spi_done(); CS_H();
    wr_cmd(0x2B);
    DC_DAT(); CS_L();
    spi_wr(y0 >> 8); spi_wr(y0 & 0xFF); spi_wr(y1 >> 8); spi_wr(y1 & 0xFF);
    spi_done(); CS_H();
    wr_cmd(0x2C);                            /* RAMWR: pixels follow */
}

void GC9A01_Backlight(uint8_t on)
{
    if (on) DL_GPIO_setPins(GPIO_LCD_PORT, GPIO_LCD_LCD_BLK_PIN);
    else    DL_GPIO_clearPins(GPIO_LCD_PORT, GPIO_LCD_LCD_BLK_PIN);
}

void GC9A01_Init(void)
{
    DL_SPI_enable(LCD_SPI_INST);
    /* hardware reset */
    RES_H(); delay_ms(10);
    RES_L(); delay_ms(20);
    RES_H(); delay_ms(120);
    gc9a01_init_seq();
}

void GC9A01_FillScreen(uint16_t color)
{
    uint8_t hi = (uint8_t)(color >> 8), lo = (uint8_t)(color & 0xFF);
    gc9a01_set_window(0, 0, LCD_W - 1, LCD_H - 1);
    DC_DAT(); CS_L();
    for (uint32_t i = 0; i < (uint32_t)LCD_W * LCD_H; i++) { spi_wr(hi); spi_wr(lo); }
    spi_done(); CS_H();
}

void GC9A01_FillRect(int16_t x, int16_t y, int16_t w, int16_t h, uint16_t color)
{
    if (w <= 0 || h <= 0) return;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > LCD_W) w = LCD_W - x;
    if (y + h > LCD_H) h = LCD_H - y;
    if (w <= 0 || h <= 0) return;
    uint8_t hi = (uint8_t)(color >> 8), lo = (uint8_t)(color & 0xFF);
    gc9a01_set_window(x, y, x + w - 1, y + h - 1);
    DC_DAT(); CS_L();
    for (uint32_t i = 0; i < (uint32_t)w * h; i++) { spi_wr(hi); spi_wr(lo); }
    spi_done(); CS_H();
}

void GC9A01_DrawPixel(int16_t x, int16_t y, uint16_t color)
{
    if (x < 0 || y < 0 || x >= LCD_W || y >= LCD_H) return;
    uint8_t hi = (uint8_t)(color >> 8), lo = (uint8_t)(color & 0xFF);
    gc9a01_set_window(x, y, x, y);
    DC_DAT(); CS_L();
    spi_wr(hi); spi_wr(lo);
    spi_done(); CS_H();
}

