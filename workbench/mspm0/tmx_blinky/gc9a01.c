void GC9A01_DrawChar(int16_t x, int16_t y, char ch, uint16_t fg, uint16_t bg, uint8_t scale)
{
    if (ch < 0x20 || ch > 0x7E) ch = ' ';
    if (scale < 1) scale = 1;
    const uint8_t *g = FONT8x8[(uint8_t)ch - 0x20];
    for (uint8_t row = 0; row < 8; row++) {
        uint8_t bits = g[row];
        for (uint8_t col = 0; col < 8; col++) {
            uint16_t c = (bits & (1u << col)) ? fg : bg;
            if (c == 0xFFFE) continue;               /* 0xFFFE == transparent bg sentinel */
            GC9A01_FillRect(x + col * scale, y + row * scale, scale, scale, c);
        }
    }
}

void GC9A01_DrawString(int16_t x, int16_t y, const char *s, uint16_t fg, uint16_t bg, uint8_t scale)
{
    if (scale < 1) scale = 1;
    while (*s) {
        GC9A01_DrawChar(x, y, *s, fg, bg, scale);
        x += 8 * scale;                              /* 8px cell */
        s++;
    }
}

void GC9A01_DrawStringCentered(int16_t y, const char *s, uint16_t fg, uint16_t bg, uint8_t scale)
{
    int len = 0; const char *p = s; while (*p++) len++;
    int16_t w = (int16_t)(len * 8 * scale);
    GC9A01_DrawString((LCD_W - w) / 2, y, s, fg, bg, scale);
}
