#ifndef MAGNET_H
#define MAGNET_H
/*
 * magnet.h - 电磁铁通道驱动（板载第三颗 DRV8231）= 阶梯 7 的"手"
 *
 * 硬件事实（真值源 = SSOT §B / 载板 §5.8，v1.3 现板上就有，不用加任何硬件）:
 *   IN1 = PB0 (TIMA1_C0, PWM)   IN2 = **板上直接接 GND ⇒ 只能单向**
 *   12V 直供                    电流采样 IPROPI = PA24 (ADC0 通道 3 = ADC_CUR 的 MEM2)
 *
 * ── 为什么要做"先满占空吸合、再降到保持占空" ──
 *   吸合需要克服气隙（磁阻大），要大电流；吸住之后气隙≈0、磁阻骤降，维持同样的吸力只需小得多的
 *   电流。一直给满占空的代价是**发热**（线圈铜损 ∝ I²R，而 12V 直供、没有电流环限流），
 *   赛场上连续吸放十几次就可能烫手甚至掉吸力（铜电阻随温度上升 ⇒ 电流下降 ⇒ 吸力下降）。
 *   所以 magnet_on() 是"满占空 CFG_MAG_PULL_MS 毫秒 → 自动降到 CFG_MAG_HOLD_PCT"。
 *   （这是驱动电磁阀/电磁铁的常规做法，TI 应用笔记 slvae59《Using Motor Drivers to Drive
 *     Solenoids》讲的就是 pull-in / hold 与续流；本工程按该思路实现，**参数未实测**。）
 *
 * ── ⚠ 一条必须说清的事：**电流判不出"球吸住了没"** ──
 *   电机的电流 ∝ 扭矩，所以负载会体现在电流上；**电磁铁不是**。它在固定占空下的稳态电流
 *   ≈ V/R，与"有没有吸住铁块"基本无关。铁块靠近改变的是**电感**（磁路闭合 ⇒ L 变大），
 *   而 L 只影响 PWM 纹波与电流上升的快慢，不影响稳态平均值。
 *   ⇒ 所以本模块的电流读数能回答的是：**线圈到底通电了没 / 线断了没 / 驱动工作了没**
 *      （0mA = 没通电或断线，这是真有用的自检）；
 *      它**不能**回答"吸住了没"。真要判"吸住了没"，用清单里那个**光电传感器（#30）**：
 *      球到位就遮光。别在赛场上花时间试图从电流里读出吸持状态 —— 那条路物理上就不通。
 *   （上面这段是物理推断 + DRV8231 真值表推断，`待实测`；实测方法：吸/不吸各测一次稳态电流，
 *     若两者差在噪声内(±40~100mA，见 config.h CUR_AVG_N)，即证实此结论。）
 *
 * ── 单向的两个后果（硬件决定，固件改不了）──
 *   ① 没有反向励磁 ⇒ **放不掉的风险真实存在**：断电后靠自然退磁 + 剩磁，小钢球可能仍粘着。
 *      对策是机械的（加一点非磁性垫片拉开气隙 / 靠车体加速度甩掉），不是固件的。
 *   ② IN2=0 时 DRV8231 只剩 coast(00) 与 forward(10) 两态 ⇒ PWM 关断期是 fast decay
 *      （电流经体二极管回灌电源），纹波比 slow decay(11 制动态) 大。想要 slow decay 得改硬件。
 *
 * 状态: 2026-07-27 新建。**编译级；真机零验证**（PB0 从未输出过、PA24 从未采过）。
 *       上板第一步见 README 的 "阶梯 7 bring-up"：先 `E1` 听/摸有没有吸力 + 看电流跳不跳。
 */
#include <stdint.h>

typedef enum {
    MAG_OFF = 0,        /* 断电 */
    MAG_PULL,           /* 吸合中：满占空，持续 CFG_MAG_PULL_MS */
    MAG_HOLD            /* 保持中：降到 CFG_MAG_HOLD_PCT */
} magnet_state_t;

/* 初始化：占空归 0 再启动定时器（上电绝不许默认吸合——电磁铁一通电就在发热）。 */
void magnet_init(void);

/* 吸：进入 PULL（满占空），到时由 magnet_tick() 自动转 HOLD。 */
void magnet_on(void);

/* 放：立刻断电，回 MAG_OFF。 */
void magnet_off(void);

/* 直接给占空（0..100，会被 CFG_MAG_PWM_CAP 限幅）。调试/整定吸力用；
 * 它会把状态机置成 HOLD 语义（不再自动降额），所以**长时间用它要自己盯着热**。 */
void magnet_set(int pct);

/*
 * 每个主循环拍调用一次，now_ms = 当前毫秒（car.c 传 g_st/ST_PER_MS）。
 * 负责两件事：
 *   ① PULL 到时降额成 HOLD；
 *   ② **通电总时长上限**（CFG_MAG_MAX_ON_MS）到了就强制断电并打一行日志。
 *      这道闸门的理由与运动超时自停完全一样：没有它，一次"忘记发 E0"或脚本崩掉
 *      就是线圈一直通电发热，而且**没有任何现象提醒你**（电磁铁不动不响）。
 */
void magnet_tick(uint32_t now_ms);

magnet_state_t magnet_state(void);
int  magnet_duty(void);                 /* 当前占空 % */
uint32_t magnet_on_ms(uint32_t now_ms); /* 已通电多久 ms（OFF 时为 0） */

/* 线圈电流 (mA)。⚠ 它证明的是"通电了/没断线"，**不是"吸住了"**（见文件头）。
 * 读一次会触发一整条 ADC 序列（约 CUR_AVG_N × 3 通道），别放在高频环里调。 */
int32_t magnet_current_ma(void);

/* 供上层做"线圈健康"自检：吸合中电流低于此值 = 大概率断线/驱动没工作。 */
int magnet_coil_ok(int32_t ma);

#endif /* MAGNET_H */
