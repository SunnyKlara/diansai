#ifndef CMD_GATE_H
#define CMD_GATE_H

/*
 * cmd_gate.h - 串口命令的格式门（纯逻辑、不依赖 HAL ⇒ 可 PC 单测）
 *
 * 它修的是一个**已坐实的真 bug**，不是防御性编程：
 *   车载 ESP-01S 每次上电都从 TXD 吐一段 boot 日志，灌进 MCU 的 UART3(PB3)。
 *   而命令解析原本"遇 \r\n 就把整行首字符当命令"⇒ 日志里 `tail 0` / `tail 4` / `tail 0`
 *   三行的首字符正好是 `t`(设定目标值) ⇒ **每次 ESP 上电必静默改目标 + 清 PID 积分**；
 *   同段日志还有纯乱码行，撞上 `x`/`y` 就是直接驱动电机。
 *   真车症状 = "跑着突然停 / 目标莫名归零 / PID 积分被清"，而查电机、查编码器、查 PID
 *   永远查不到——凶手在 ESP 的启动日志里。
 *   证据：650 字节真实 boot 流（workbench/天猛星主板平台/无线遥测_ESP01S_boot字节证据.txt），
 *   PC 回放显示 22 行会被当命令、其中 3 行触发 `t`。
 *
 * 门的规则：只接受 `<字母>[-][数字...]`，另**单独放行一个裸 `?`**（查询状态），可选 `#` 前缀。
 *   过门：m3 / t900 / p150 / z / **?** / v100 / r-30 / s-1 … 现有全部脚本发的就是这个形状
 *   拒掉：`tail 0`(有空格) / `chksum 0xf3`(有空格+字母) / `ready`(字母后面还是字母) / 乱码行
 *
 * ⚠️ `?` 这个特例是 PC 单测抓出来的：`?` 不是字母，纯"字母+数字"规则会把它拒掉，
 *    而 `uart_send.ps1 -Cmd "?"` 是最常用的一条命令。原设计文档写"? 100% 兼容"但
 *    PowerShell 模拟器那 8 条测试用例里恰好没有 `?` ⇒ 这个不兼容一直没被发现。
 *    （教训：兼容性声明要按"实际会发的命令全集"逐条测，别按印象。）
 *
 * 为什么放在头文件里做 static inline：本工程铁律"算法层不依赖 HAL、可 PC 单独编译验证"。
 * 这样 car.c 与 pc_test/test_cmd_gate.c 用的是**同一份代码**，而不是两份互相抄的实现
 * （esp_fake_mcu.ps1 就吃过这个亏：它自称 faithful copy，而当时固件里那份原件根本不存在）。
 */

/* 返回 1 = 形状合法、可以交给 run_cmd()；0 = 拒掉并计入 rej 计数。
 * 注意：本函数**只看形状、不看语义** —— 字母是不是已知命令由 run_cmd 的 switch/default 兜。 */
static inline int cmd_format_ok(const char *s, int n)
{
    int i = 0;

    if (n <= 0) return 0;
    if (s[i] == '#') i++;                 /* 可选帧头(将来若要强制帧头, 把这里改成必需即可) */
    if (i >= n) return 0;                 /* 只有一个 '#' */

    /* 特例: 裸 '?' = 查询状态。必须"后面什么都没有", 免得放宽成任意含 ? 的行 */
    if (s[i] == '?') return (i + 1 == n) ? 1 : 0;

    /* 第 1 个字符必须是字母 = 命令字 */
    if (!((s[i] >= 'a' && s[i] <= 'z') || (s[i] >= 'A' && s[i] <= 'Z'))) return 0;
    i++;

    if (i == n) return 1;                 /* 单字母无参命令: z / o / k / g */

    if (s[i] == '-') i++;                 /* 允许负参数: s-1 / r-30 */
    /* ⚠️ 光有负号没数字必须拒 —— PC 单测抓到的: `t-` 会让 parse_int("-") 返回 0,
     * 等于静默把目标设成 0(和那个 boot 日志 bug 一模一样的后果)。 */
    if (i == n) return 0;

    for (; i < n; i++)                    /* 其余必须全是数字 */
        if (s[i] < '0' || s[i] > '9') return 0;

    return 1;
}

#endif /* CMD_GATE_H */
