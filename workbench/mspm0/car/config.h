/* ==================== 5. 位置环精定位 ==================== */

/* 死区前馈(%)：[实测] 电机死区 ≈10% PWM，位置内环按**位置误差方向**叠此值推越死区
 * （⚠ 不能按"速度PID输出符号"叠——末端过零翻号会把快电机搞成狂震）。整定值 12。
 * 运行时命令 w<v> 可改。 */
#define CFG_POS_FF_DZ      12

/* 速度环 PWM 死区补偿。`W<%>` 设置**运动时的最小 PWM 地板**，不是无条件相加：
 * - W0 = 完全关闭（包括下面的 breakaway），严格退回旧行为；
 * - 目标非零且 PID 输出尚未越过 W 时，按目标方向抬到 W；高速段 PID 输出本来就大于 W，
 *   因此不会像旧 additive 方案那样把整段转向速度一起抬高。
 * [真机 2026-07-27] additive W10：j90 到 89.8°且无 STALL；反向 j-90 过冲后卡在 -95.0°。
 * W12 把主转向加快并恶化到 -103.3°；W15 虽拉回 2.1°，仍在 -93.8° STALL。
 * ⇒ 默认仍保留 0，待下方 breakaway 方案双向复验后才锁定最终 W。 */
/* [真机整定 2026-07-28 新板落地] **=10**。三趟单变量对照（`j90`，脱缆，车对齐地面直线）：
 *   Kd0.25 + W0  -> 94.6°(超调 4.6°) FAIL=STALL
 *   Kd0.60 + W0  -> 77.1°(欠调12.9°) 更差：D 刹得更早, 于是离目标 13° 就停死
 *   Kd0.25 + W10 -> **90.2°(误差 0.2°)**, 末端连续 PWM:0,0 + yaw 恒定, 干净到位不摆  <= 锁死
 * ⇒ 两次 STALL 的共同因是**静摩擦起转, 不是超调**: W=0 时末端小指令(4.5°×Kp2.5≈11RPM ≈4.5%PWM)
 *   跨不过 ≈10% 的电机死区, 于是停在目标前/后都动不了。**W 是使能项、不是调优项**, 必须先开它才轮到调 D。
 *   (实测可见 W 在干活: 末端 PWM 被抬到 -30,24 / -33,30 = breakaway 地板量级。) */
#define CFG_DRV_FF_DZ       10

/* 静摩擦起转地板：仅在 W>0、目标非零且该轮 |rpm| < 阈值时生效；一旦轮子动起来，
 * 自动退回上面的动态 W 地板。四个方向不能共用一个数：落地单轮实测 12% 时 M1- 仅 1rpm，
 * 四轮原地对转中 M1-/M2+ 在 22% 和 25% 均高电流零转，而 -30/+30 能起转，故保持 30%。
 * M1+/M2- 的单轮 12% 结论不能代表落地双轮回修：20% 虽把左转 720° 从 0/5 DONE 提升到
 * 3/5 DONE，但失败段在持续 +20/-20 时仍静止并 STALL；30% 是现有唯一已证可静态起转值。
 * 这不是持续占空：速度非零后即退出，再回到 W10 的动态地板，避免全程抬高转速。
 * ⚠ M1+/M2-=30% 为本轮唯一改动，待重新烧录后双向 j90 + 多圈真机复验。 */
#define CFG_DRV_BREAKAWAY_RPM      3.0f
#define CFG_DRV_BREAKAWAY_M1_POS   30
#define CFG_DRV_BREAKAWAY_M1_NEG   30
#define CFG_DRV_BREAKAWAY_M2_POS   30
#define CFG_DRV_BREAKAWAY_M2_NEG   30

/* 到位死区(counts)：|位置误差| < 此值即停 + 复位速度PID，防末端抖/creep。
 * [实测] 15（≈7° @800cpr）；两轮实际到位 ±6~15counts。运行时命令 e<v> 可改。 */
#define CFG_POS_TOL        15

/* ==================== 6. IMU / 姿态（航向闭环的地基） ==================== */

/* 姿态解算节拍(ms)。5ms=200Hz: 原地转角速度可达 ~300dps, 200Hz 下每拍仅 1.5°, 积分够细。
 * [估计] attitude_update 含软浮点 atan2f/sqrtf(M0+ 无 FPU), 单次开销量级"几千周期" ⇒ 200Hz 下
 *   占 CPU 个位数百分比。**这是纸面估算, 没有实测过**(要实测就在该节拍里翻转一个 GPIO 用示波器量
 *   脉宽, 或统计 SysTick 计数差)。若上板后发现遥测变慢/环变软, 第一件事就是把这里降到 10ms(100Hz)。
 * ⚠ dt 用 SysTick 真实经过时间(不是这个常数), 因为 yaw 积分对 dt 的敏感度是 1:1 —— dt 错 20% 转角就错 20%
 *   (本工程已被"数主循环拍×假设1ms"坑过一次: 报的 RPM 虚高 5x)。 */
#define CFG_IMU_MS          5

/* 互补滤波系数(pitch/roll 用): 越接近 1 越信陀螺(短期), 1-alpha 信加速度(长期消漂)。
 * 200Hz 下 0.98 对应时间常数 ≈ dt*alpha/(1-alpha) ≈ 0.25s。yaw 不用它(无绝对参考、纯积分)。 */
#define CFG_ATT_ALPHA       0.98f

/* ★ yaw 取哪个轴的陀螺: 0=X 1=Y 2=Z。**这两个宏只是上电默认值, 待 L1/L2 实测确定后回填**。
 * 定法(L1): 车按实际安装姿态平放 → `g` 看哪个加速度轴 ≈ ±1000mg, 那个就是竖直轴。
 * 实现: attitude_axis_map() 做**循环置换**把该轴搬到 slot2 再喂 attitude_update(det=+1, 不破坏
 *   pitch/roll 手性); car.c 只是选轴/选符号, attitude.c 与贴装朝向解耦(PC 单测覆盖三种轴)。
 * ⚠ **定轴过程不要靠改这里重烧** —— 用串口命令 `a<0|1|2>` / `s<1|-1>` 在线切换(改完必须重发 `k`
 *   标定, 固件会自动清零偏并提示)。原因: 试轴要多次, 连续快烧是本工程把芯片怼进 lockup 的头号原因。
 * [估计] 默认 2 = attitude.h 原假设"IMU 平贴车底、Z 朝上"; 但 2026-07-27 实测重力主要落在 +Y
 *   (857mg, Z 仅 427mg) ⇒ 很可能要改成 1。**注意那次读数时板子是斜立的, 不能直接当结论**, 必须
 *   按实际安装姿态平放重测(这也是为什么 L1 的前置是"平放", 不是"随便放")。 */
#define CFG_YAW_AXIS        2

/* ★ yaw 符号: +1 或 -1。**待 L2 实测确定**(绕竖直轴逆时针/左转, yaw 应变正; 反了就填 -1)。
 * 只作用在喂给积分的那一路角速度上, 不影响 pitch/roll。运行时命令 `s<1|-1>`。
 * ⚠ 竖直轴若朝下(平放时该轴读 -1000mg 而非 +1000mg), 符号会跟着反 —— 由本宏吸收即可;
 *   但那种装法下 pitch/roll 会是镜像的(az≈-1g ⇒ roll≈±180°)。车题不用 pitch/roll, 可接受, 记着即可。 */
#define CFG_YAW_SIGN        (+1)

