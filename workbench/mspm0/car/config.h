/* =1 把 UART3 编进固件（遥测镜像 + 无线收命令）。=0 则完全退回"只有有线调试口"的老行为。 */
#define CFG_ESP_UART_EN     1

/* 开机默认往哪些口打印（位掩码，运行时可用 `l<mask>` 改）：1=有线 DAP / 2=无线 ESP / 3=两个都打。
 * 默认 3 的理由：脱缆落地时无线是唯一通道，而"忘记打开"这种失误只会在最需要的时候才暴露。
 * ⚠️ **代价是每个字符发两遍。[实测 2026-07-27]**：`f5` 下量遥测行率 —— 单口 345 行/3s(115/s, 8.7ms/行)
 *    vs 双发 195 行/3s(65/s, 15.4ms/行) ⇒ **第二路的边际代价 = +6.7 ms/行**。
 *    与理论吻合：遥测行约 76 字节 × 10bit ÷ 115200 = 6.6ms（原先按 62 字节估的 5.4ms 偏小，已按实测改）。
 *    10Hz 遥测无所谓；**整定用 `f20`(50Hz) 以上就该用 `l1`/`l2` 只留一个口**（否则一行占掉 15.4ms/20ms）。
 *    控制环在 SysTick 中断里，不受主循环阻塞影响（这是它敢阻塞式发送的前提）。 */
#define CFG_UART_SINKS_BOOT 3

/* 上电静默窗(ms)：这段时间内 RX 字节只读走、不解析成命令。
 * 为什么必须有：ESP 与 MCU 同电源上电，ESP 每次启动都从 TXD 吐一段 boot 日志，
 * 其中 `tail 0` / `tail 4` 三行的首字符正好是命令 `t`(设定目标) ⇒ 会静默改目标 + 清 PID 积分。
 * 这不是猜的：已用 650 字节真实 boot 流在 PC 上回放坐实（esp_boot_risk.ps1 -ReplayHex）。
 * 2000ms 覆盖 ESP boot 全程（实测 ~600ms 内结束）。[保护] */
#define CMD_MUTE_MS         2000

