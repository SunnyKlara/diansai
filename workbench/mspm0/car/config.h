/* ── 阿克曼几何：轴距 ──
 * **实测 137mm**（2026-07-27 用户量：前轮轮心到后轮轮心 13.7cm）。这是自行车模型里唯一的几何量:
 *   转弯半径 R = L / tan(delta)   ·   偏航角速度 w = v * tan(delta) / L
 *   反解(上层要 w、当前速度 v ⇒ 该给多少前轮转向角): delta = atan(w * L / v)
 * ⚠️ 137mm 是很短的轴距，两个后果都要记住:
 *   ① **好消息**: delta=25° 时 R = 137/tan25° ≈ 294mm ⇒ 最小转弯半径约 29cm，比想象的灵活;
 *   ② **坏消息**: 短轴距 ⇒ 同样的转向角误差会更快地把车头带偏（w 与 1/L 成正比）
 *      ⇒ 航向环增益要比长轴距车更小、且**低速时 delta 会算得很大**（v 在分母上），
 *        所以反解那步必须限幅到 CFG_SERVO_MAX_DEG，并给 v 设下限防除零。
 * ⚠️ 只有轴距、没有轮距: 单舵机拉杆做的是**机械近似阿克曼**，左右前轮的差角由拉杆几何决定、
 *   固件管不着也不需要管 ⇒ 自行车模型（用单一等效前轮角）就是正确的抽象层级。
 */
#define CFG_WHEELBASE_MM   137.0f   /* 实测 2026-07-27（卷尺，±2mm）*/

