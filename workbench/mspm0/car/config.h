/* ==================== 1. 时钟与时基 ==================== */

/* CPU 主频。SysConfig 默认 32MHz（MFCLK/SYSOSC），改时钟树要同步改这里。 */
#define CPUCLK_HZ     32000000UL

/* 控制主时基 = SysTick 中断频率。编码器采样也在这个 ISR 里（不放主循环——阻塞式 UART
 * 遥测会 stall 几 ms → 漏采/混叠 → 速度乱跳 → 环整不动）。
 * [实测] 5kHz 远超电机最高换向率（~1k/s @60%PWM），不混叠。 */
#define ST_HZ         5000UL
/* 每 ms 的 SysTick 拍数，调度用。
 * ⚠ **`ST_HZ` 必须是 1000 的整数倍** —— 这里是整数除法，5000/1000=5 恰好整除。若哪天改成
 *   4500，`ST_PER_MS` 会被截成 4（而不是 4.5），于是**所有按 ms 排的节拍、超时闸门、dt 换算
 *   全部静默偏 12.5%**，没有任何报错。真要用非整数倍频率，就得把时基换算改成先乘后除。 */
#define ST_PER_MS     (ST_HZ / 1000UL)

/* 各任务周期（真实 ms；调度读 SysTick 计数，不数会被 LCD/UART 拖慢的主循环拍）。
 * [实测] 旧版"拍数×假设1ms"被 LCD 逐像素重绘拖到 ~5ms/拍 → 报的 RPM 虚高 5x、环退化到 4Hz。 */
#define SPEED_MS      50     /* 速度测量窗 + 速度环周期(~20Hz) */
#define POS_MS        100    /* 位置外环周期(~10Hz) */
#define PRINT_MS      100    /* 遥测默认周期，运行时可用 f<ms> 改（整定抓暂态用 f20） */
#define DISP_MS       500    /* LCD 刷新周期：逐像素重绘 ~100ms/次，必须调慢否则拖死控制环 */

/* ==================== 2. 执行器（PWM / 电机） ==================== */

/* PWM 周期计数，必须与 car.syscfg 的 timerCount 一致（1600 @32MHz ≈ 20kHz，静音）。 */
#define MOTOR_PWM_PERIOD  1600

/* PWM 占空上限(%)。[保护] MG310P20 是 7.4V 电机、母线 12V → 封顶 60% 使平均 ≈7.2V，
 * 防过热/损耗。换 7.4V 供电后才可放开。 */
#define PWM_CAP       60

/* ---- 2.1 线束朝向（板级事实，不是可调参数）--------------------------------------------
 * 目标约定（全工程依赖它）：**正占空 ⇒ 两侧车轮都物理前进 ⇒ 两侧编码器都数正**。
 * `car_drive_mix(v,w)` 直行时给两侧都是 +v，所以这个约定不成立的话 v>0 会让车原地转；
 * 而编码器符号若与电机反，速度环就是**正反馈**（PID 越推越远，一路顶到饱和 —— 老板真踩过）。
 *
 * ⚠ 为什么放在这里而不是改 encoder.c 的 QDEC 表 / 改 motor.c：
 *   2026-07-28 换新打板载板后发现，老板时代那些"直接改表/改映射"的补丁**全部反了**，
 *   而注释还写着"已翻转"这种换板即失效的假话 —— 补丁藏在查找表里 = 下一块板必然踩坑。
 *   所以线束朝向收敛到这 4 个有名字的常量，并在 SSOT §C 登记。
 * ⚠ **动过电机线或编码器 A/B 线，必须回来改这里并重新按下面的判据实测**，别靠记忆。
 *
 * [实测 2026-07-28，新打板两驱载板，轮子架空、`tools/spin_watch.ps1` + 人眼判方向]
 *   左 M1 @+25%：物理**前进**，编码器 20/20 趟共 dC=-123296（**负**）⇒ 电机对、编码器反
 *   右 M2 @+25%：物理**后退**，编码器 12/12 趟共 dC= -93924（**负**，即诚实）⇒ 电机反、编码器对
 *   两趟另一路增量分别为 -55 / 0 ⇒ 跨通道独立。
 * 复验判据：`spin_watch.ps1 -Motor L|R` 跑一趟，人看轮子顶点朝车头还是车尾；
 *   物理前进而 dC 为负 ⇒ 该侧 ENC 符号取 -1；物理后退 ⇒ 该侧 MOT 符号取 -1。 */
#define CFG_MOT_SIGN_L   (+1)   /* 左电机极性：实测 +占空即前进 ⇒ 不翻 */
#define CFG_MOT_SIGN_R   (-1)   /* 右电机极性：实测 +占空后退 ⇒ 翻 */
#define CFG_ENC_SIGN_L   (-1)   /* 左编码器：前进却数负 ⇒ 翻 */
#define CFG_ENC_SIGN_R   (+1)   /* 右编码器：诚实（翻完右电机后前进即数正）⇒ 不翻 */

/* ==================== 3. 反馈（编码器 / 电流） ==================== */

/* 输出轴每圈计数（4x 正交解码后）。
 * [标定] 2026-07-27 真机手转（换 JGA27-310R-74 · 20:1 · 7.4V · 450RPM 之后，两轮各 10 圈）：
 *        左轮 9525/10 = 952.5 · 右轮 9570/10 = 957.0 ⇒ **取均值 954.75**（两侧只差 0.47%）。
 *        结构上对应 12线 × 4x × 20:1 = 960，实测为其 99.2~99.7%（差值 = 人工停位对记号的误差）。
 *        同次校验：只转一侧时另一侧计数增量 0（映射正确、无串扰）；静止漂移 0。
 * ⚠ 旧值 800 是**上一只电机 MG310P20** 的（10线×4×20:1），换电机后差 19.3% —— 别再用。
 * ⚠ 它只影响 RPM 标尺（速度环的"100rpm"是多少、遥测 V: 显示多少）。
 *   `ENC_COUNTS_PER_MM` 是直接测 counts→mm 的，**不经过本值**，所以这 0.5% 的余量对里程无影响。
 * ⚠ 改了本值必须**重编 + 重烧**才算数（makefile 的 config.h 依赖已修，但仍要看到 Building car.obj）；
 *   且速度环增益是旧电机+旧标尺整定的 ⇒ 重烧后要重新整定，别拿旧增益当达标。 */
#define ENC_CPR       954.75f

/* 里程标定：编码器计数 → 毫米（把打滑一起吃进这个数里）。
 * [标定] 2026-07-27 三趟落地实测（脱缆、前轮手扳正）。**取两趟 `n300` 的值 5.109**：
 *        `n300` #1: 1609.5 counts / 卷尺 315mm = 5.1095
 *        `n300` #2: 1583.5 counts / 卷尺 310mm = 5.1081     <- 两者差 0.03%
 *        `m7 v80` 2s: 2044 counts / 卷尺 394mm = 5.1878     <- 离群 1.5%, 按 5.109 反推该走 400mm,
 *                     与量到的 394mm 差 6mm = 参考点误差量级 ⇒ 判为那次卷尺偏小, 不采用。
 * 交叉验证（比"再拟合一趟"硬）：两趟计数差 26 counts，按 5.109 换算应差 5.1mm，
 *        而卷尺量到的差正好是 5mm ⇒ **编码器预测的差值与实测差值对上，重复性成立**。
 * ⚠ 但两次卷尺用的是同一套参考点约定，**绝对标尺仍只有一次独立测量**；想收紧就跑一趟 1m
 *   （距离越长，卷尺 ±5mm 的相对权重越小）。
 * 自洽校验：2044 ÷ ENC_CPR(954.75) = 2.141 圈 ⇒ 等效周长 184.0mm ⇒ **等效轮径 58.6mm**
 *        （与常见 58/60mm 轮吻合；若与实物差 >10% 说明打滑或量错参考点，应重跑而不是硬写）。
 * ⚠ **别再打磨这个数** —— 实测误差预算：命令 300mm 实走 310~315mm，其中**滑行 14~16mm、
 *   标定只贡献 1~4mm** ⇒ 收益在 CFG_NAV_COAST_MM，不在这里。
 * ⚠ 它**不经过 `ENC_CPR`**（直接 counts↔mm），所以 ENC_CPR 的 0.5% 余量不影响里程。
 * ⚠ 换轮/换胎/换地面（地毯 vs 瓷砖）后打滑变了，此值要重标。 */
#define ENC_COUNTS_PER_MM   5.109f

/* 转角标定（**编码器兜底路径**，陀螺不可用时才用）：(右轮增量 − 左轮增量) / 度。
 * ⬜ **未标定**（做法：原地转 360°（地上贴胶带对齐），读左右计数增量，(dR−dL)/360）。
 * 为 0 = 没有兜底 ⇒ 陀螺没标定时 nav 的转角会直接判 NO_HDG 而不是瞎转。
 * ⚠ 它的前提是"轮子不打滑"，而原地转恰恰是最容易打滑的动作（坑库有条）⇒ **永远是次选**，
 *   heading_ok=1 时 nav.c 一定用陀螺。它的价值在于"陀螺坏了/轴没定"时阶梯 4 不至于全废。
 * 标法已脚本化：`nav_test.ps1 -CalTurn 360`（开环原地转，读左右计数差；给 -MeasDeg 量角器读数
 * 才算真值，不给则只是拿陀螺当参照、脚本会判 INCONCLUSIVE）。 */
#define ENC_COUNTS_PER_DEG  0.0f

/* 电流采样：ADC 原始值 → mA 的除数。I(mA) = raw*3300/CUR_MA_DIV。
 * [估计] 按 IPROPI 1575µA/A × R=680Ω 纸面值算得 4387；不同模块批次 R 有差异，
 * 需串万用表实测 1~2 个工作点回归校准后改这里。 */
#define CUR_MA_DIV    4387u

/* 电流采样次数（每次读取内部连采取平均）。
 * [实测] PWM 斩波让 IPROPI 呈脉冲，单次异步采会在 0~峰值间狂跳(t150 时抖 0~627mA)；
 * 16 次平均 ≈1.5ms/次、把尖峰压掉，但**残余噪声仍 ±40~100mA**——彻底干净的正解是
 * "ADC 触发同步到 PWM 定相采样"（未做，见跨题坑库）。 */
#define CUR_AVG_N     16

