/*
 * config.h - 天猛星 MSPM0 小车【全部可调参数集中处】
 *
 * 为什么有这个文件（工作台规范 §2 铁律 + 校赛B 教训）：
 *   ① 赛场调参只翻这一个文件，不去 450 行的 car.c 里找宏；
 *   ② "真机整定达标 → 当场回填锁死"要有唯一落点，否则达标值只活在串口窗口里；
 *   ③ 每个值旁边写清**出处**（实测 / 标定 / 保护 / 估计），答辩和复盘时说得清。
 *
 * 事实真值源 = `.kiro/steering/工程事实SSOT.md`（引脚 / 已标定参数 / 烧录命令 / 禁忌）。
 * 改这里的值 → 必须重编 + 重烧 + **物理 RST** 才算生效（openocd 软复位起不来，见 SSOT §D2）。
 *
 * 标注约定：[实测] 真机测出来的  [标定] 真机标定值  [保护] 安全限幅  [估计] 未实测/待校准
 */
#ifndef CONFIG_H
#define CONFIG_H

/* ==================== 1. 时钟与时基 ==================== */

/* CPU 主频。SysConfig 默认 32MHz（MFCLK/SYSOSC），改时钟树要同步改这里。 */
#define CPUCLK_HZ     32000000UL

/* 控制主时基 = SysTick 中断频率。编码器采样也在这个 ISR 里（不放主循环——阻塞式 UART
 * 遥测会 stall 几 ms → 漏采/混叠 → 速度乱跳 → 环整不动）。
 * [实测] 5kHz 远超电机最高换向率（~1k/s @60%PWM），不混叠。 */
#define ST_HZ         5000UL
#define ST_PER_MS     (ST_HZ / 1000UL)   /* 每 ms 的 SysTick 拍数，调度用 */

/* 各任务周期（真实 ms；调度读 SysTick 计数，不数会被 LCD/UART 拖慢的主循环拍）。
 * [实测] 旧版"拍数×假设1ms"被 LCD 逐像素重绘拖到 ~5ms/拍 → 报的 RPM 虚高 5x、环退化到 4Hz。 */
#define SPEED_MS      50     /* 速度测量窗 + 速度环周期(~20Hz) */
#define POS_MS        100    /* 位置外环周期(~10Hz) */
#define PRINT_MS      100    /* 遥测默认周期，运行时可用 f<ms> 改（整定抓暂态用 f20） */
#define DISP_MS       500    /* LCD 刷新周期：逐像素重绘 ~100ms/次，必须调慢否则拖死控制环 */

/* ==================== 2. 执行器（PWM / 电机） ==================== */

/* PWM 周期计数，必须与 car.syscfg 的 timerCount 一致（1600 @32MHz ≈ 20kHz，静音）。 */
#define MOTOR_PWM_PERIOD  1600

/* PWM 占空上限(%)。[保护] MG310P20 是 7.4V 电机、母线 12V → 封顶 60% 使平均 ≈7.2V，
 * 防过热/损耗。换 7.4V 供电后才可放开。 */
#define PWM_CAP       60

/* ==================== 3. 反馈（编码器 / 电流） ==================== */

/* 输出轴每圈计数（4x 正交解码后）。
 * [标定] 2026-07-25 真机手转 8 圈增量 6402 → 6402/8 = 800（原按减速比估的 899 偏高 ~12%）。 */
#define ENC_CPR       800.0f

/* 里程标定：编码器计数 → 毫米。⬜ **未标定**（做法：落地直行一段，卷尺量实际距离，
 * counts/实测mm，把滑移一起吃进去；标完把 0 换成实测值并 commit）。
 * 为 0 表示"未标定"，上层要走"走 N mm"必须先标。 */
#define ENC_COUNTS_PER_MM   0.0f

/* 电流采样：ADC 原始值 → mA 的除数。I(mA) = raw*3300/CUR_MA_DIV。
 * [估计] 按 IPROPI 1575µA/A × R=680Ω 纸面值算得 4387；不同模块批次 R 有差异，
 * 需串万用表实测 1~2 个工作点回归校准后改这里。 */
#define CUR_MA_DIV    4387u

/* 电流采样次数（每次读取内部连采取平均）。
 * [实测] PWM 斩波让 IPROPI 呈脉冲，单次异步采会在 0~峰值间狂跳(t150 时抖 0~627mA)；
 * 16 次平均 ≈1.5ms/次、把尖峰压掉，但**残余噪声仍 ±40~100mA**——彻底干净的正解是
 * "ADC 触发同步到 PWM 定相采样"（未做，见跨题坑库）。 */
#define CUR_AVG_N     16

/* ==================== 4. 控制环增益（真机整定值，改前先看 SSOT §C） ==================== */

/* --- 电流环 [未整定·技术储备] ---
 * 暂缓原因：反馈需 ADC-PWM 同步定相采（现仅 16 次平均）、整定需负载（空转电机恒扭矩
 * 会一直加速到 PWM 饱和、守不住电流）。两个前置齐了再拾起。 */
#define CFG_KP_CUR    0.20f
#define CFG_KI_CUR    0.02f
#define CFG_KD_CUR    0.00f

/* --- 速度环 [实测达标] ---
 * 2026-07-26：修完时基 5x bug 后反馈小 5x → Kp 0.03 抬到 0.15。
 * 实测 std~3%、松手过冲 276→207（Kp=0.20 会振）。 */
#define CFG_KP_SPD    0.15f
#define CFG_KI_SPD    0.02f
#define CFG_KD_SPD    0.00f

/* --- 位置环（外环，输出速度目标 RPM）[实测达标] ---
 * 纯 PD，不加 I（电机死区下积分易 hunt）。阶跃 800counts 两轮到位 ±9counts。 */
#define CFG_KP_POS    0.20f
#define CFG_KI_POS    0.00f
#define CFG_KD_POS    0.05f

/* 位置外环输出限幅（速度目标 RPM 上下限）。[保护] 防外环一上来就要求全速。 */
#define CFG_POS_VOUT_MAX   300.0f

/* ==================== 5. 位置环精定位 ==================== */

/* 死区前馈(%)：[实测] 电机死区 ≈10% PWM，位置内环按**位置误差方向**叠此值推越死区
 * （⚠ 不能按"速度PID输出符号"叠——末端过零翻号会把快电机搞成狂震）。整定值 12。
 * 运行时命令 w<v> 可改。 */
#define CFG_POS_FF_DZ      12

/* 到位死区(counts)：|位置误差| < 此值即停 + 复位速度PID，防末端抖/creep。
 * [实测] 15（≈7° @800cpr）；两轮实际到位 ±6~15counts。运行时命令 e<v> 可改。 */
#define CFG_POS_TOL        15

/* ==================== 6. IMU / 姿态（航向闭环的地基） ==================== */

/* 姿态解算节拍(ms)。5ms=200Hz: 原地转角速度可达 ~300dps, 200Hz 下每拍仅 1.5°, 积分够细。
 * [估计] attitude_update 含软浮点 atan2f/sqrtf(M0+ 无 FPU), 单次开销量级"几千周期" ⇒ 200Hz 下
 *   占 CPU 个位数百分比。**这是纸面估算, 没有实测过**(要实测就在该节拍里翻转一个 GPIO 用示波器量
 *   脉宽, 或统计 SysTick 计数差)。若上板后发现遥测变慢/环变软, 第一件事就是把这里降到 10ms(100Hz)。
 * ⚠ dt 用 SysTick 真实经过时间(不是这个常数), 因为 yaw 积分对 dt 的敏感度是 1:1 —— dt 错 20% 转角就错 20%
 *   (本工程已被"数主循环拍×假设1ms"坑过一次: 报的 RPM 虚高 5x)。 */
#define CFG_IMU_MS          5

/* 互补滤波系数(pitch/roll 用): 越接近 1 越信陀螺(短期), 1-alpha 信加速度(长期消漂)。
 * 200Hz 下 0.98 对应时间常数 ≈ dt*alpha/(1-alpha) ≈ 0.25s。yaw 不用它(无绝对参考、纯积分)。 */
#define CFG_ATT_ALPHA       0.98f

/* ★ yaw 取哪个轴的陀螺: 0=X 1=Y 2=Z。**这两个宏只是上电默认值, 待 L1/L2 实测确定后回填**。
 * 定法(L1): 车按实际安装姿态平放 → `g` 看哪个加速度轴 ≈ ±1000mg, 那个就是竖直轴。
 * 实现: attitude_axis_map() 做**循环置换**把该轴搬到 slot2 再喂 attitude_update(det=+1, 不破坏
 *   pitch/roll 手性); car.c 只是选轴/选符号, attitude.c 与贴装朝向解耦(PC 单测覆盖三种轴)。
 * ⚠ **定轴过程不要靠改这里重烧** —— 用串口命令 `a<0|1|2>` / `s<1|-1>` 在线切换(改完必须重发 `k`
 *   标定, 固件会自动清零偏并提示)。原因: 试轴要多次, 连续快烧是本工程把芯片怼进 lockup 的头号原因。
 * [估计] 默认 2 = attitude.h 原假设"IMU 平贴车底、Z 朝上"; 但 2026-07-27 实测重力主要落在 +Y
 *   (857mg, Z 仅 427mg) ⇒ 很可能要改成 1。**注意那次读数时板子是斜立的, 不能直接当结论**, 必须
 *   按实际安装姿态平放重测(这也是为什么 L1 的前置是"平放", 不是"随便放")。 */
#define CFG_YAW_AXIS        2

/* ★ yaw 符号: +1 或 -1。**待 L2 实测确定**(绕竖直轴逆时针/左转, yaw 应变正; 反了就填 -1)。
 * 只作用在喂给积分的那一路角速度上, 不影响 pitch/roll。运行时命令 `s<1|-1>`。
 * ⚠ 竖直轴若朝下(平放时该轴读 -1000mg 而非 +1000mg), 符号会跟着反 —— 由本宏吸收即可;
 *   但那种装法下 pitch/roll 会是镜像的(az≈-1g ⇒ roll≈±180°)。车题不用 pitch/roll, 可接受, 记着即可。 */
#define CFG_YAW_SIGN        (+1)

/* 陀螺角速度死区(dps): 去零偏后 |ω| 小于此值按 0 处理, 防残余噪声被积分成漂移。
 * [估计] 先给 0（=纯积分）, **等 L3 静态漂移实测完再定值**(参考工程用 0.25dps 做到 0.003°/50s)。
 * 先测再给值, 别拍脑袋——否则测不出"死区到底有没有必要"。 */
#define CFG_GYRO_DEADBAND_DPS   0.0f

/* 零偏标定采样数(命令 `k`): 200Hz × 400 = 2s。标定期间车必须完全静止。
 * ⚠ 陀螺零偏随温度漂 ⇒ **赛场每次上电/每个任务前都要重标, 别用上次的值**。 */
#define CFG_IMU_CAL_N       400

/* ==================== 7. 运动安全：超时自停（落地前的硬前置） ====================
 *
 * 为什么必须有: 在此之前"停车"完全依赖 PC 端补发 `z` —— 脚本崩、串口断、agent 被超时 kill、
 *   人手忙不过来, 车就一直跑(桌面是撞墙, 地面是冲出去)。这是清单里唯一"不做会有物理损失"的一条。
 *
 * 两个独立的闸门, 分别挡两种不同的失败(缺一个都留洞):
 *   ① 静默超时 CFG_RUN_MS_*  —— 时钟被"收到任何一条命令"刷新 ⇒ 语义 = **没人说话 N 秒就停**。
 *      挡的是"无人值守"(脚本崩/串口断/agent 被 kill)。
 *      ⚠ 已知取舍(诚实写下): 若 PC 端在**周期性轮询**(如每秒一个 `?`), 它会持续刷新这个时钟 ——
 *      此时靠 ② 兜底。之所以选"任何命令都刷新"而不是"只有运动命令刷新": 整定时人要连发
 *      p/i/d 改增益, 若这些不刷新, 模式会在你打字中途被踢回 IDLE, 反而逼人去关掉这个保护。
 *   ② 硬上限 CFG_RUN_MS_HARDCAP —— 从**进入该模式**那一刻算起, 到点无条件停, 任何命令都不能续命。
 *      挡的是"有人在但拦不住"(车已跑飞/人手忙不过来)。想继续就重新进模式, 这是有意的摩擦。
 *
 * 触发时: 回 MODE_IDLE + 清掉所有残留指令 + 打印是哪个闸门触发的(便于事后归因, 别静默停机)。
 */

/* 静默超时(ms), 按模式给 —— 越"无反馈/越危险"的模式给越短。
 * [保护] 开环直驱(m4/m5)没有任何反馈, 出问题只会一路顶到 PWM 上限 ⇒ 给最短。
 * [保护] m7 闭环差速是**落地跑直线**用的, 2m 需要好几秒 ⇒ 给最长(但仍受 ② 硬上限约束)。 */
#define CFG_RUN_MS_OPEN     1500   /* m4 OPEN  直驱 */
#define CFG_RUN_MS_DUAL     1500   /* m5 DUAL  左右独立直驱 */
#define CFG_RUN_MS_CURR     3000   /* m1 电流环(储备, 未整定) */
#define CFG_RUN_MS_SPD      4000   /* m2 速度环: 整定时要看完一个阶跃 */
#define CFG_RUN_MS_POS      5000   /* m3 位置环: 自己会到位停, 给宽些 */
#define CFG_RUN_MS_DRIVE    2500   /* m6 开环差速(离地验分组用) */
#define CFG_RUN_MS_DRIVE_CL 6000   /* m7 闭环差速: 落地 2m 直线的预算 */

/* 硬上限(ms): 进模式起算, 无条件停。[保护] 参考工程用 15s 长跑 guard, 取同量级。
 * ⚠ 落地跑若需要 >6s, 改 CFG_RUN_MS_DRIVE_CL; 但**别把硬上限调得很大**, 它是最后一道墙。 */
#define CFG_RUN_MS_HARDCAP  15000

/* ==================== 8. 调试开关 ==================== */

/* =1 开启编码器分层探针（开机直读引脚原始电平 + 软件轮询边沿 + ISR 计数三视图，
 * 全程不驱动电机）。排查完必须改回 0，否则默认 build 进不了控制固件。 */
#define ENC_PROBE     0

/* ==================== 9. 串口命令健壮化（为 ESP-01S 无线遥测铺路） ==================== */
/* 上电静默期(ms): MCU 上电后这段时间内只把 UART RX 字节读走、不解析成命令。
 * 为什么要它: ESP-01S 的 TXD 接到 MCU 的 UART RX 后, ESP 每次上电/掉压复位都会吐一段
 * boot 日志, 其中 "tail 0" / "tail 4" 三行的首字符正好是本固件的命令 't'(设定目标值),
 * 而 parse_int(" 0") 遇空格即返回 0 => 每次 ESP 上电静默执行 3 次「改目标 + 清PID积分」,
 * 真车上表现为"跑着突然停/目标莫名归零", 查电机/编码器/PID 永远查不到。
 * 实测 ESP boot 输出 ~600ms 内结束(650 字节), 取 2000ms 留足余量。
 * 配套第二层 = car.c 的 cmd_format_ok() 严格格式门(只收 "<字母>[-][数字...]", 允许 '#' 前缀),
 * 该门控逻辑已用真实 boot 字节流在 PC 上回放验证(旧逻辑触发3次't', 新逻辑零命令通过)。
 * 证据 + 完整说明: workbench/天猛星主板平台/无线遥测_ESP01S链路.md §5 */
#define CMD_MUTE_MS   2000UL

#endif /* CONFIG_H */
