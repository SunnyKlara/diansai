#define CFG_RUN_MS_OPEN     1500   /* m4 OPEN  直驱: 最危险(全开环无反馈), 无脚本需要长跑 -> 保持最短 */
#define CFG_RUN_MS_DUAL     4000   /* m5 DUAL  左右独立直驱(xtalk 串扰测试 3s) */
#define CFG_RUN_MS_CURR     4000   /* m1 电流环(iloop 3s; 电流环本身是储备、未整定) */
#define CFG_RUN_MS_SPD      6000   /* m2 速度环(tune_step 3s; 整定要看完一个阶跃) */
#define CFG_RUN_MS_POS      8000   /* m3 位置环(pos_step 5s + 手推刚度测试要按住好几秒) */
#define CFG_RUN_MS_DRIVE    2500   /* m6 开环差速: 只用于离地验分组, 短 */
#define CFG_RUN_MS_DRIVE_CL 6000   /* m7 闭环差速: 落地 2m 直线的预算 */
#define CFG_RUN_MS_NAV     10000   /* m8/m9 车级导航: **发一条 `n1000` 就没人再说话了**, 所以这道闸门
                                    * 必须够长 —— 它不是"多久算超时", 而是"这趟最多允许跑多久"。
                                    * 量级依据: 巡航 120RPM、轮周长≈204mm ⇒ ≈408mm/s ⇒ 2m 约 5s;
                                    * 80RPM 时约 7.4s。留到 10s。
                                    * ⚠ **上限仍是 CFG_RUN_MS_HARDCAP=15s, 抬这个值也绕不过它** ⇒
                                    *   单趟超过 ~4m 就得先想清楚(拆成两段, 或有意识地抬硬上限)。
                                    * ⚠ 导航正常结束靠的是 nav 自己判到位, 这道闸门只是兜底。 */

