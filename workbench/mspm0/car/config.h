#define CFG_POS_TOL        15

/* ==================== 6. IMU / 姿态（航向闭环的地基） ==================== */

/* 姿态解算节拍(ms)。5ms=200Hz: 原地转角速度可达 ~300dps, 200Hz 下每拍仅 1.5°, 积分够细。
 * [估计] attitude_update 含软浮点 atan2f/sqrtf(M0+ 无 FPU), 单次开销量级"几千周期" ⇒ 200Hz 下
 *   占 CPU 个位数百分比。**这是纸面估算, 没有实测过**(要实测就在该节拍里翻转一个 GPIO 用示波器量
 *   脉宽, 或统计 SysTick 计数差)。若上板后发现遥测变慢/环变软, 第一件事就是把这里降到 10ms(100Hz)。
 * ⚠ dt 用 SysTick 真实经过时间(不是这个常数), 因为 yaw 积分对 dt 的敏感度是 1:1 —— dt 错 20% 转角就错 20%
 *   (本工程已被"数主循环拍×假设1ms"坑过一次: 报的 RPM 虚高 5x)。 */
#define CFG_IMU_MS          5

/* 互补滤波系数(pitch/roll 用): 越接近 1 越信陀螺(短期), 1-alpha 信加速度(长期消漂)。
 * 200Hz 下 0.98 对应时间常数 ≈ dt*alpha/(1-alpha) ≈ 0.25s。yaw 不用它(无绝对参考、纯积分)。 */
#define CFG_ATT_ALPHA       0.98f

/* ★ yaw 取哪个轴的陀螺: 0=X 1=Y 2=Z。**这两个宏只是上电默认值, 待 L1/L2 实测确定后回填**。
 * 定法(L1): 车按实际安装姿态平放 → `g` 看哪个加速度轴 ≈ ±1000mg, 那个就是竖直轴。
 * 实现: attitude_axis_map() 做**循环置换**把该轴搬到 slot2 再喂 attitude_update(det=+1, 不破坏
 *   pitch/roll 手性); car.c 只是选轴/选符号, attitude.c 与贴装朝向解耦(PC 单测覆盖三种轴)。
 * ⚠ **定轴过程不要靠改这里重烧** —— 用串口命令 `a<0|1|2>` / `s<1|-1>` 在线切换(改完必须重发 `k`
 *   标定, 固件会自动清零偏并提示)。原因: 试轴要多次, 连续快烧是本工程把芯片怼进 lockup 的头号原因。
 * [估计] 默认 2 = attitude.h 原假设"IMU 平贴车底、Z 朝上"; 但 2026-07-27 实测重力主要落在 +Y
 *   (857mg, Z 仅 427mg) ⇒ 很可能要改成 1。**注意那次读数时板子是斜立的, 不能直接当结论**, 必须
 *   按实际安装姿态平放重测(这也是为什么 L1 的前置是"平放", 不是"随便放")。 */
#define CFG_YAW_AXIS        2

/* ★ yaw 符号: +1 或 -1。**待 L2 实测确定**(绕竖直轴逆时针/左转, yaw 应变正; 反了就填 -1)。
 * 只作用在喂给积分的那一路角速度上, 不影响 pitch/roll。运行时命令 `s<1|-1>`。
 * ⚠ 竖直轴若朝下(平放时该轴读 -1000mg 而非 +1000mg), 符号会跟着反 —— 由本宏吸收即可;
 *   但那种装法下 pitch/roll 会是镜像的(az≈-1g ⇒ roll≈±180°)。车题不用 pitch/roll, 可接受, 记着即可。 */
#define CFG_YAW_SIGN        (+1)

/* 陀螺角速度死区(dps): 去零偏后 |ω| 小于此值按 0 处理, 防残余噪声被积分成漂移。
 * [估计] 先给 0（=纯积分）, **等 L3 静态漂移实测完再定值**(参考工程用 0.25dps 做到 0.003°/50s)。
 * 先测再给值, 别拍脑袋——否则测不出"死区到底有没有必要"。 */
#define CFG_GYRO_DEADBAND_DPS   0.0f

/* 静止标定采样数(命令 `k`): 200Hz × 400 = 2s。标定期间车必须**完全静止**且处于**真实行驶姿态**。
 * 这一次标定同时产出两样东西:
 *   ① 陀螺零偏(随温度漂 ⇒ **赛场每次上电/每个任务前都要重标**, 别用上次的值);
 *   ② **天顶方向向量 `up`**(加速度均值归一化) —— 偏航角速度 = 角速度在它上的投影。
 * ⇒ 姿态要求只有一条: **标定时的姿态 = 以后跑的姿态**; 板子装歪、车垫不平都不影响(见 attitude.h)。
 * ⚠ 因此"用手扶着标定"是**半可用**的: 加速度均值(天顶方向)容忍轻微晃动, 但**陀螺零偏容忍不了**——
 *   手的微小转动会被当成零偏烙进去, 之后表现为 yaw 一直漂。要零偏准, 必须放桌上松手。 */
#define CFG_IMU_CAL_N       400

/* 开机默认显示页: 0=编码器计数页 1=水平仪页。
 * [选 1 的理由] 开机必然在 IDLE, 此时最该回答的两个问题正是"IMU 活着吗 / 车平不平";
 *   而一旦发出任何运动命令, 固件会自动切回计数页(水平仪页仅 IDLE 可用)。
 *   附带好处: 不依赖串口就能看到定轴所需的画面(串口是独占资源, 常被占)。 */
#define CFG_DISP_BOOT_PAGE  1

/* ==================== 6.5 水平仪页（LCD 定轴助手）阈值 ====================
 *
 * 用途: 定轴(L1)要求"车按实际安装姿态放平", 但人在挪车时**没有任何反馈**, 只能反复跑脚本猜。
 *   屏上画一个圆形水平仪(小球+同心容差环), 边挪边看, 进到绿环就够了。
 *
 * ★ 阈值不是拍脑袋, 是从 `imu_axis.ps1 -Step L1` 的判据反算的:
 *   L1 要求"竖直轴 |a| >= 900mg 且其余两轴 <= 250mg", 其中**"其余轴 <=250mg" 是更紧的那条** ——
 *   250mg / 1000mg = 0.25 => 单轴倾角 asin(0.25) ≈ 14.5°。所以 14° 是"L1 能通过"的门槛。
 *
 * ★ 但"能通过"不等于"应该满足于此" —— 倾角 θ 会给偏航角**永久的系统性比例误差**:
 *   竖直轴偏离真竖直 θ 时, 该轴测到的偏航角速度被缩放 cos(θ)（还会串入另两轴的分量）。
 *     θ=14° -> cos=0.970 -> 转 90° 少 2.7°(3.0% 误差)
 *     θ= 5° -> cos=0.996 -> 转 90° 少 0.34°
 *     θ= 2° -> cos=0.999 -> 转 90° 少 0.05°
 *   ⚠ 关键: 车的安装姿态是**固定**的 ⇒ 这个误差不是随机噪声, 是**每一次转弯都同方向偏**, 会累积。
 *   所以推荐做到 <=2°(优)/<=5°(良), 14° 只是底线。
 *
 * ★ 更要紧的一条判读(别搞反): 车放在**水平桌面/地面**上、按正常行驶姿态摆好时, 小球就应该接近中心。
 *   若此时小球明显偏出, 说明 **IMU 板相对底盘装歪了** —— 正解是**机械上重新固定板子**,
 *   而不是把车垫斜去让小球居中(那样车一落地又歪回去, 且引入一个假的"已校准"错觉)。
 */
#define CFG_LEVEL_OK_DEG        2.0f    /* 优: 转 90° 的比例误差 <0.1% */
#define CFG_LEVEL_GOOD_DEG      5.0f    /* 良: <0.4% */
#define CFG_LEVEL_PASS_DEG      14.0f   /* 底线: = L1 判据的 250mg, 仅够"认出哪个轴竖直" */
#define CFG_LEVEL_PX_PER_DEG    4       /* 屏上每度多少像素(4 => 14° 环半径 56px, 圆屏放得下) */
/* |a| 合理带(mg): 越界说明在动/有振动/定标不对, 此时倾角读数不可信, 页面会提示而不给判定 */
#define CFG_LEVEL_A_MIN_MG      850
#define CFG_LEVEL_A_MAX_MG      1150

/* ==================== 7. 运动安全：超时自停（落地前的硬前置） ====================
 *
 * 为什么必须有: 在此之前"停车"完全依赖 PC 端补发 `z` —— 脚本崩、串口断、agent 被超时 kill、
 *   人手忙不过来, 车就一直跑(桌面是撞墙, 地面是冲出去)。这是清单里唯一"不做会有物理损失"的一条。
 *
 * 两个独立的闸门, 分别挡两种不同的失败(缺一个都留洞):
 *   ① 静默超时 CFG_RUN_MS_*  —— 时钟被"收到任何一条命令"刷新 ⇒ 语义 = **没人说话 N 秒就停**。
 *      挡的是"无人值守"(脚本崩/串口断/agent 被 kill)。
 *      ⚠ 已知取舍(诚实写下): 若 PC 端在**周期性轮询**(如每秒一个 `?`), 它会持续刷新这个时钟 ——
 *      此时靠 ② 兜底。之所以选"任何命令都刷新"而不是"只有运动命令刷新": 整定时人要连发
 *      p/i/d 改增益, 若这些不刷新, 模式会在你打字中途被踢回 IDLE, 反而逼人去关掉这个保护。
 *   ② 硬上限 CFG_RUN_MS_HARDCAP —— 从**进入该模式**那一刻算起, 到点无条件停, 任何命令都不能续命。
 *      挡的是"有人在但拦不住"(车已跑飞/人手忙不过来)。想继续就重新进模式, 这是有意的摩擦。
 *
 * 触发时: 回 MODE_IDLE + 清掉所有残留指令 + 打印是哪个闸门触发的(便于事后归因, 别静默停机)。
 */

/* 静默超时(ms), 按模式给 —— 越"无反馈/越危险"的模式给越短。
 * [保护] 开环直驱(m4/m5)没有任何反馈, 出问题只会一路顶到 PWM 上限 ⇒ 给最短。
 * [保护] m7 闭环差速是**落地跑直线**用的, 2m 需要好几秒 ⇒ 给最长(但仍受 ② 硬上限约束)。 */
/* ⚠ 这些值不是拍脑袋: 已对着**现有整定脚本的静默采集时长**留了余量, 否则会把跑到一半的测试掐掉,
 *   人会以为"固件出 bug 了"然后干脆关掉这个保护 —— 安全机制被绕过就等于没有。对照:
 *     tune_step 3.0s(m2) · iloop 3s(m1) · xtalk 3s(m5) · pos_step 5s(m3) —— 均留 >1s 余量。 */
#define CFG_RUN_MS_OPEN     1500   /* m4 OPEN  直驱: 最危险(全开环无反馈), 无脚本需要长跑 -> 保持最短 */
#define CFG_RUN_MS_DUAL     4000   /* m5 DUAL  左右独立直驱(xtalk 串扰测试 3s) */
#define CFG_RUN_MS_CURR     4000   /* m1 电流环(iloop 3s; 电流环本身是储备、未整定) */
#define CFG_RUN_MS_SPD      6000   /* m2 速度环(tune_step 3s; 整定要看完一个阶跃) */
#define CFG_RUN_MS_POS      8000   /* m3 位置环(pos_step 5s + 手推刚度测试要按住好几秒) */
#define CFG_RUN_MS_DRIVE    2500   /* m6 开环差速: 只用于离地验分组, 短 */
#define CFG_RUN_MS_DRIVE_CL 6000   /* m7 闭环差速: 落地 2m 直线的预算 */

/* 硬上限(ms): 进模式起算, 无条件停, `h` 也绕不过。[保护] 参考工程用 15s 长跑 guard, 取同量级。
 * ⚠ 落地跑若需要 >6s, 改 CFG_RUN_MS_DRIVE_CL; 但**别把硬上限调大**, 它是最后一道墙。
 * ⚠ **已知交互(别当 bug)**: `disturb_test.ps1` 默认静默采集 20s(示例给 30s) > 本上限 ⇒ 跑到 15s 会被
 *   截断并打 `RUN TIMEOUT (HARDCAP)`。抗扰测试实际只需几秒(推-松-看恢复), 所以处置是**把
 *   `-Seconds` 降到 ≤14**, 而不是抬高这道墙。 */
#define CFG_RUN_MS_HARDCAP  15000

