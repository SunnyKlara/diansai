/* ---- 2. 反例: ESP boot 日志典型行 + 畸形输入 ---- */
static void test_boot_noise_rejected(void)
{
    printf("test_boot_noise_rejected (ESP boot 日志与畸形输入必须全拒):\n");
    expect("tail 0", 0);                   /* ★ 就是这行害的: 首字符 t = 设定目标 */
    expect("tail 4", 0);                   /* ★ */
    expect("chksum 0xf3", 0);
    expect("csum 0x22", 0);
    expect("load 0x40100000, len 2592, room 16 ", 0);
    expect("ready", 0);                    /* 字母后面还是字母 */
    expect("OK", 0);
    expect("AT+RST", 0);
    expect("2nd boot version : 1.7(5d6f877)", 0);
    expect("SPI Speed : 40MHz", 0);
    expect("jump to run user1 @ 1000", 0);
    expect(">", 0);                        /* 提示符: 非字母且非 '?' */
    expect("Ai-Thinker Technology Co. Ltd.", 0);
    /* 畸形/边界 */
    expect("", 0);
    expect("#", 0);                        /* 只有帧头 */
    expect("t 900", 0);                    /* 中间有空格 */
    expect("t900x", 0);                    /* 数字后面还有字母 */
    expect("t-", 0);                       /* 只有负号没有数字 -> 形状不完整, 应拒 */
    expect("-30", 0);                      /* 没有命令字 */
    expect("??", 0);                       /* '?' 只放行裸的一个 */
    expect("t9?0", 0);
}

