/*
 * test_cmd_gate.c - cmd_gate.h(串口命令格式门) 的 PC 单元测试
 *
 * 编译运行(在本目录):
 *   gcc -O2 -Wall -I.. -o test_cmd_gate test_cmd_gate.c
 *   .\test_cmd_gate.exe            (Windows)   /   ./test_cmd_gate   (Linux)
 *
 * 为什么值得单测: 这个门挡的是一个**已在真机坐实的 bug** —— 车载 ESP-01S 每次上电
 * 从 TXD 吐的 boot 日志会灌进 MCU 的 UART3(PB3), 而旧解析"遇 \r\n 就把整行首字符当命令",
 * 于是 `tail 0` / `tail 4` / `tail 0` 三行触发 `t`(设定目标) => 静默改目标 + 清 PID 积分。
 *
 * 覆盖:
 *   1  正例: 现有 6 个 .ps1 工具实际会发的命令全集, 必须 100% 过门
 *   2  反例: ESP boot 日志的典型行 + 常见畸形输入, 必须全拒
 *   3  回归: 拿 650 字节**真实 boot 流**(无线遥测_ESP01S_boot字节证据.txt 原始字节)
 *      按固件的行切分规则跑一遍 —— 旧逻辑会触发 3 次 't', 新逻辑必须 0 次命令
 *
 * 边界(诚实): 本测试验的是"门的判断"与"行切分规则"。上电静默窗(CMD_MUTE_MS)依赖 SysTick,
 * 双口 RX 依赖 UART 外设, 那两部分只能真机验 => 见 无线遥测_ESP01S链路.md §7。
 */
#include "cmd_gate.h"
#include <stdio.h>
#include <string.h>

static int g_fail = 0;

static void expect(const char *s, int want)
{
    int got = cmd_format_ok(s, (int)strlen(s));
    if (got == want) {
        printf("  [PASS] %-24s -> %s\n", s, got ? "ACCEPT" : "reject");
    } else {
        printf("  [FAIL] %-24s -> %s (want %s)\n", s, got ? "ACCEPT" : "reject",
               want ? "ACCEPT" : "reject");
        g_fail++;
    }
}

/* ---- 1. 正例: 六个 .ps1 工具实际会发的命令全集(逐个从脚本里对过) ---- */
