/* 镜像 car.c 里 feed_cmd_stream() 的行切分规则: 缓冲 16 字节、最多存 15、遇 \r 或 \n 成行。
 * gate=0 = 旧逻辑(无门), gate=1 = 现在的逻辑。返回"会触发几条命令", 并统计首字母分布。 */
static int replay_boot(int gate, char *letters, int letters_sz)
{
    char buf[16];
    int  len = 0, fired = 0, nl = 0;
    size_t i;

    for (i = 0; i < sizeof(BOOT); i++) {
        unsigned char ch = BOOT[i];
        if (ch == '\r' || ch == '\n') {
            if (len > 0) {
                if (!gate || cmd_format_ok(buf, len)) {
                    fired++;
                    if (nl < letters_sz - 1) letters[nl++] = buf[0];
                }
            }
            len = 0;
        } else if (len < 15) {
            buf[len++] = (char)ch;
        }
    }
    letters[nl] = '\0';
    return fired;
}

static void test_real_boot_stream_regression(void)
{
    char old_letters[64], new_letters[64];
    int old_fired, new_fired, t_count = 0, i;

    printf("test_real_boot_stream_regression (650 字节真实 boot 流):\n");

    old_fired = replay_boot(0, old_letters, (int)sizeof(old_letters));
    new_fired = replay_boot(1, new_letters, (int)sizeof(new_letters));

    for (i = 0; old_letters[i]; i++) if (old_letters[i] == 't') t_count++;

    printf("    旧逻辑(无门): %d 行会被当命令执行, 首字母序列 = \"%s\"\n", old_fired, old_letters);
    printf("    其中 't'(设定目标 + 清 PID 积分) 被触发 %d 次\n", t_count);
    printf("    新逻辑(有门): %d 行通过\n", new_fired);

    if (t_count == 3) {
        printf("  [PASS] 复现了原始故障: 旧逻辑触发 3 次 't'(与文档记录一致)\n");
    } else {
        printf("  [FAIL] 期望旧逻辑触发 3 次 't', 实际 %d 次 —— 测试数据或切分规则变了\n", t_count);
        g_fail++;
    }
    if (new_fired == 0) {
        printf("  [PASS] 格式门把 650 字节 boot 流里的每一行都拒掉了(0 条命令通过)\n");
    } else {
        printf("  [FAIL] 仍有 %d 行过门: \"%s\"\n", new_fired, new_letters);
        g_fail++;
    }
}

