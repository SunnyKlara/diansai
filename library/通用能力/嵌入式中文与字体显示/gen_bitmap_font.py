#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
嵌入式中文 / 大号数字 位图字体生成器（参考骨架）
把 PC 上的 TrueType 字体渲染成 C 数组，供 MCU 屏(OLED/圆屏/TFT)直接 blit。

⚠️ 参考骨架（未在本仓库真机验证）：按你的屏改下面 CONFIG → 运行 → 生成物【上屏验证过】再当"已完成"（守北极星）。
依赖：Pillow   ->   pip install pillow
用法：python gen_bitmap_font.py
原理与决策见同目录 README.md。
"""

from PIL import Image, ImageFont, ImageDraw

# ================= CONFIG（按你的屏和需求改这里） =================
FONT_PATH = r"C:\Windows\Fonts\msyhbd.ttc"   # 字体。楷体 simkai.ttf；开源无版权顾虑用思源黑体/文泉驿
FONT_SIZE = 24                                # 字号，按屏分辨率调（240 圆屏 2-4 字词组 ~24；OLED ~16）
FORMAT    = "rgb565"                          # "rgb565"(彩屏) 或 "1bpp"(单色 OLED, 输出 XBM 供 u8g2 drawXBM)
RGB565_BIG_ENDIAN = True                      # 彩屏字节序，多数驱动大端；上屏花屏/错色就翻这个
TINT      = (255, 255, 255)                   # 字色(白)。语义色示例：警告琥珀(255,180,0) / 报警红(255,0,0)
THRESHOLD = 128                               # 1bpp 阈值：灰阶 > 它算亮点
OUT_C     = "font_data.c"

# (符号名[必须 ASCII], 要显示的文字) —— 只有列在这里的字会被生成
LABELS = [
    ("target",  "目标"),
    ("current", "当前"),
    ("error",   "误差"),
    ("unit_cm", "cm"),
    # 新增一行即可，如 ("mode", "悬浮")
]
# ================================================================


def render_gray(text):
    """渲染文字到灰度图并紧密裁剪（去空白边），返回裁剪后的 'L' 模式图。抗锯齿由 PIL 自带。"""
    font = ImageFont.truetype(FONT_PATH, FONT_SIZE)
    canvas = Image.new("L", (FONT_SIZE * (len(text) + 2), FONT_SIZE * 2), 0)  # 黑底，留足画布防裁切
    ImageDraw.Draw(canvas).text((FONT_SIZE // 2, FONT_SIZE // 4), text, fill=255, font=font)
    bbox = canvas.getbbox()          # 非零像素的最小外接矩形
    if bbox is None:
        raise ValueError(f"渲染为空：'{text}'（字体缺该字？换字体或确认源文件是 UTF-8）")
    return canvas.crop(bbox)


def to_rgb565(img):
    px, (w, h), out = img.load(), img.size, []
    tr, tg, tb = TINT
    for y in range(h):
        for x in range(w):
            g = px[x, y]                                  # 0..255 抗锯齿灰阶
            r8, g8, b8 = tr * g // 255, tg * g // 255, tb * g // 255
            v = ((r8 >> 3) << 11) | ((g8 >> 2) << 5) | (b8 >> 3)
            out += ([(v >> 8) & 0xFF, v & 0xFF] if RGB565_BIG_ENDIAN else [v & 0xFF, (v >> 8) & 0xFF])
    return out, w, h


def to_xbm_1bpp(img):
    """XBM：行主序、每行按字节对齐、每字节 8 像素 LSB 优先。配 u8g2 u8g2_DrawXBM。"""
    px, (w, h), out = img.load(), img.size, []
    row_bytes = (w + 7) // 8
    for y in range(h):
        for bx in range(row_bytes):
            b = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < w and px[x, y] > THRESHOLD:
                    b |= (1 << bit)
            out.append(b)
    return out, w, h


def emit(name, data, w, h):
    sym = f"img_{name}_{w}_{h}"
    lines = [f"// {name}: {w}x{h}  {FORMAT}", f"const unsigned char {sym}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return sym, "\n".join(lines)


def main():
    parts = ["// AUTO-GENERATED by gen_bitmap_font.py — DO NOT EDIT BY HAND",
             "// 改字/字号/颜色请改脚本 LABELS/CONFIG 后重跑", ""]
    externs = []
    for name, text in LABELS:
        img = render_gray(text)
        data, w, h = (to_rgb565(img) if FORMAT == "rgb565"
                      else to_xbm_1bpp(img) if FORMAT == "1bpp"
                      else (_ for _ in ()).throw(ValueError("FORMAT 只支持 rgb565 / 1bpp")))
        sym, block = emit(name, data, w, h)
        parts += [block, ""]
        externs.append(f"extern const unsigned char {sym}[{len(data)}];  // {text}  {w}x{h}")

    with open(OUT_C, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))

    print(f"[OK] 写出 {OUT_C}（{len(LABELS)} 个词组，FORMAT={FORMAT}）")
    print("\n== 贴进你的显示头文件(.h) ==")
    print("\n".join(externs))
    print(f"\n提醒：把 {OUT_C} 加进工程源文件列表(Keil/CubeIDE/CCS 或 CMake SRCS)；上屏验证后再当'已完成'。")


if __name__ == "__main__":
    main()
